# dict 查找是大小写敏感的，CONFERENCE_CYCLES 的键为了代码里好读保留了
# 混合大小写（例如 "USENIX Security"），所以另建一份全大写索引专供查询用，
# 不能指望在查询时把 key 转大写再去查混合大小写的字典（这是已修过的一个坑）。
_UPPER_INDEX: dict[str, tuple[float, str]] = {
    k.upper(): v for k, v in CONFERENCE_CYCLES.items()
}

# 常见的写法差异留一点容错，键值都用全大写
_ALIASES: dict[str, str] = {
    "SP": "S&P", "IEEE S&P": "S&P", "IEEESP": "S&P",
    "USENIX SEC": "USENIX SECURITY", "USENIXSECURITY": "USENIX SECURITY",
    "ACMMM": "ACM MM", "MM": "ACM MM",
    "KDD": "SIGKDD",
}


def lookup_conference_cycle(abbr: str) -> tuple[float, str] | None:
    """按缩写查典型周期，大小写和常见变体不敏感。"""
    if not abbr:
        return None
    key = abbr.strip().upper()
    key = _ALIASES.get(key, key)
    return _UPPER_INDEX.get(key)
